import { GlassRing } from '@/components/glass-ring'
import { wineDetails } from '@/lib/tasting/display'
import { SCALES, type Scale } from '@/lib/tasting/presets'
import { formatScore, toScale, type WineResult } from '@/lib/tasting/results'
import type { TastingStatus } from '@/lib/tasting/rules'
import type { RingState } from '@/server/participant-view'
import { cn } from '@/lib/utils'

export type TableWine = { id: string; position: number; title: string; ratingCount: number }

/**
 * Big-screen view for the table (iPad, TV): join QR before the start, progress while tasting,
 * podium at the end. Public with the code alone – so it never shows guest names or live scores.
 */
export function TableView({
  name,
  code,
  status,
  joinUrl,
  qrSvg,
  guests,
  wines,
  podium,
  scale,
}: {
  name: string
  code: string
  status: TastingStatus
  joinUrl: string
  qrSvg: string
  guests: number
  wines: TableWine[]
  podium: WineResult[] | null
  scale: Scale
}) {
  return (
    <main className="mx-auto w-full max-w-[1400px] px-4 pt-4 pb-16 sm:px-8 lg:px-12 lg:pt-8">
      <header className="flex flex-wrap items-end justify-between gap-x-8 gap-y-2">
        <h1 className="font-display text-4xl leading-[1.05] font-medium tracking-tight md:text-5xl lg:text-7xl">
          {name}
        </h1>
        <p className="text-muted-foreground lg:text-lg">{guests === 1 ? '1 Gast dabei' : `${guests} Gäste dabei`}</p>
      </header>

      {status === 'setup' && <Waiting code={code} joinUrl={joinUrl} qrSvg={qrSvg} />}
      {status === 'active' && <Progress code={code} joinUrl={joinUrl} qrSvg={qrSvg} guests={guests} wines={wines} />}
      {status === 'finished' && podium && <Podium wines={podium} scale={scale} />}
    </main>
  )
}

function Qr({ svg, url, className }: { svg: string; url: string; className?: string }) {
  return (
    <div
      role="img"
      aria-label={`QR-Code für ${url}`}
      className={cn('rounded-2xl bg-white p-4 [&>svg]:h-auto [&>svg]:w-full', className)}
      // Path data generated by our own QR library from our own URL
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  )
}

function Code({ code, className }: { code: string; className?: string }) {
  return (
    <p className={cn('font-mono tracking-[0.3em]', className)}>
      <span className="sr-only">Code </span>
      {code}
    </p>
  )
}

function Waiting({ code, joinUrl, qrSvg }: { code: string; joinUrl: string; qrSvg: string }) {
  return (
    <section className="mt-10 grid items-center gap-10 md:grid-cols-[minmax(0,1fr)_minmax(0,1fr)] lg:mt-16 lg:gap-20">
      <div>
        <p className="font-display text-3xl leading-tight text-balance md:text-4xl lg:text-5xl">Scanne den Code und mach mit.</p>
        <p className="mt-6 text-muted-foreground lg:text-lg">Oder öffne die Startseite und tippe den Code ein:</p>
        <Code code={code} className="mt-2 text-5xl lg:text-7xl" />
        <p className="mt-4 text-sm break-all text-muted-foreground">{joinUrl}</p>
      </div>
      <Qr svg={qrSvg} url={joinUrl} className="w-full max-w-[420px] justify-self-center md:justify-self-end" />
    </section>
  )
}

function ringState(count: number, guests: number): RingState {
  if (count === 0) return 'open'
  return count >= guests ? 'done' : 'incomplete'
}

function Progress({
  code,
  joinUrl,
  qrSvg,
  guests,
  wines,
}: {
  code: string
  joinUrl: string
  qrSvg: string
  guests: number
  wines: TableWine[]
}) {
  const done = wines.reduce((sum, w) => sum + Math.min(w.ratingCount, guests), 0)
  return (
    <section className="mt-10 lg:mt-14">
      <div className="flex flex-wrap items-end justify-between gap-6">
        <div>
          <h2 className="text-sm text-muted-foreground lg:text-base">So weit sind wir</h2>
          <p className="mt-1 font-display text-3xl lg:text-5xl">
            {done} von {wines.length * guests} Bewertungen
          </p>
        </div>
        {/* Late arrivals can still join */}
        <div className="flex items-center gap-4">
          <div className="text-right">
            <p className="text-sm text-muted-foreground">Noch nicht dabei?</p>
            <Code code={code} className="mt-1 text-2xl" />
          </div>
          <Qr svg={qrSvg} url={joinUrl} className="w-28 p-2 lg:w-36" />
        </div>
      </div>

      <ol className="mt-10 grid grid-cols-2 gap-x-6 gap-y-10 sm:grid-cols-3 lg:mt-14 lg:grid-cols-4 xl:grid-cols-5">
        {wines.map((w) => (
          <li key={w.id} className="flex flex-col items-center text-center">
            <GlassRing seed={w.position} state={ringState(w.ratingCount, guests)} size={140}>
              <span className="font-display text-5xl font-medium">{w.position}</span>
            </GlassRing>
            <p className="mt-3 w-full truncate font-display text-xl">{w.title}</p>
            <p className="text-sm text-muted-foreground">
              {Math.min(w.ratingCount, guests)} von {guests}
            </p>
          </li>
        ))}
      </ol>
    </section>
  )
}

function Podium({ wines, scale }: { wines: WineResult[]; scale: Scale }) {
  const ranked = wines.filter((w) => w.rank !== null)
  if (ranked.length === 0) {
    return <p className="mt-16 font-display text-3xl text-muted-foreground">Keine Bewertungen abgegeben.</p>
  }
  const [winner, ...rest] = ranked
  const score = (w: WineResult) => formatScore(toScale(w.score, scale), scale)
  const max = SCALES[scale].max

  return (
    <section className="mt-10 lg:mt-14">
      <h2 className="text-sm text-muted-foreground lg:text-base">Endergebnis</h2>
      <div className="mt-6 flex flex-col items-start gap-8 md:flex-row md:items-center lg:gap-14">
        <GlassRing seed={winner.position} size={260} animation="soak" delayMs={300}>
          <span className="flex flex-col items-center">
            <span className="font-display text-8xl font-medium">{score(winner)}</span>
            <span className="text-muted-foreground">von {max}</span>
          </span>
        </GlassRing>
        <div className="min-w-0">
          <p className="text-lg font-medium text-wine lg:text-xl">Platz {winner.rank}</p>
          <p className="text-muted-foreground lg:text-lg">{winner.label}</p>
          <p className="reveal-up font-display text-4xl leading-tight font-medium md:text-5xl lg:text-7xl" style={{ animationDelay: '700ms' }}>
            {winner.name ?? winner.label}
          </p>
          {wineDetails(winner) && <p className="mt-2 text-muted-foreground lg:text-xl">{wineDetails(winner)}</p>}
        </div>
      </div>

      {rest.length > 0 && (
        <ol className="mt-12 grid grid-cols-1 border-t border-border sm:grid-cols-2 sm:gap-x-12 lg:mt-16">
          {rest.map((w) => (
            <li key={w.wineId} className="flex items-center gap-5 border-b border-border py-4">
              <span className="w-16 shrink-0 font-medium text-wine lg:text-lg">Platz {w.rank}</span>
              <div className="min-w-0 flex-1">
                <p className="truncate font-display text-2xl lg:text-3xl">{w.name ?? w.label}</p>
                {w.name && <p className="truncate text-sm text-muted-foreground">{w.label}</p>}
              </div>
              <span className="font-display text-3xl font-medium lg:text-4xl">{score(w)}</span>
            </li>
          ))}
        </ol>
      )}
    </section>
  )
}
